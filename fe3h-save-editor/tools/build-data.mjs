/* Builds js/data-<lang>.js from the JSON in tools/sources - the same shape on both editors:

     tools/dump-sources.mjs   game's own .dat and FILE_*.dat.gz  ->  tools/sources/*.json   (this folder)
     tools/build-data.mjs     tools/sources/*.json               ->  js/data-<lang>.js
     index.html               js/data-<lang>.js                  ->  names next to every number in the save

   The .dat parsing, the LX13 message reader and the string-index arithmetic all live in dump-sources.mjs;
   this script only resolves names for one language and reshapes the tables into what the page reads.

     node tools/build-data.mjs            # every language that has a message table
     LANGS=ja node tools/build-data.mjs   # just those codes

   Output is byte-for-byte what the old .dat-driven generator produced; tools/test-codec.mjs re-checks the
   numbers themselves against a real save. */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'tools', 'sources');
const OUT = path.join(ROOT, 'js');

const read = (f) => JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8'));
const items = read('items.json'), roster = read('roster.json'), supports = read('supports.json'), glossary = read('glossary.json');

// Languages are whichever the JSON actually carries a name for, optionally narrowed by LANGS=en,ja.
const present = new Set();
for (const x of items.Items) for (const c of Object.keys(x.Names || {})) present.add(c);
for (const x of roster.Persons) for (const c of Object.keys(x.Names || {})) present.add(c);
for (const x of Object.values(glossary.Lists)) for (const c of Object.keys(x.Names || {})) present.add(c);
const wanted = (process.env.LANGS || '').split(',').map((s) => s.trim()).filter(Boolean);
const LANGS = [...present].filter((c) => !wanted.length || wanted.includes(c));
if (!LANGS.length) { console.error('nothing to build: ' + (wanted.length ? 'LANGS=' + wanted + ' is not in tools/sources' : 'tools/sources has no names')); process.exit(2); }

const pick = (names, lang) => names && (names[lang] !== undefined ? names[lang] : names.en);

for (const lang of LANGS) {
  // items: id -> { n, dur, rank, range, hit, crit, wt }. An id with no dump row is still a usable item if
  // this language has a name for it, which is how the page can name an id the dumps never covered.
  const itemDb = {};
  for (const x of items.Items) {
    const n = pick(x.Names, lang) || '';
    const hasRow = x.Durability !== undefined;
    if (!hasRow && !n) continue;
    const e = { n };
    if (hasRow) { e.dur = x.Durability; e.rank = x.Rank; e.range = x.Range; e.hit = x.Hit; e.crit = x.Crit; e.wt = x.Weight; }
    itemDb[x.Id] = e;
  }
  const chars = roster.Persons.map((p) => {
    const n = pick(p.Names, lang) || {};
    return {
      n: n.Given || '', extra: n.Title || '', surname: n.Surname || '',
      cls: p.Class, age: p.Age, gender: p.Gender, affil: p.Affiliation,
      baseHp: p.BaseHp, maxHp: p.MaxHp, growHp: p.GrowHp,
      base: p.Base, grow: p.Grow, max: p.Max, crest: p.Crest,
    };
  });
  const classes = roster.Classes.map((c) => ({
    n: pick(c.Names, lang) || '', exam: c.Exam, exp: c.Exp, baseHp: c.BaseHp,
    base: c.Base, skillBonus: c.SkillBonus, arts: c.Arts,
  }));
  const list = (key) => glossary.Lists[key].Names[lang] || glossary.Lists[key].Names.en;
  const data = {
    items: itemDb, chars, classes,
    skills: list('skills'), arts: list('arts'), magic: list('magic'), battalions: list('battalions'),
    battalionSkills: list('battalionSkills'), crests: list('crests'), affiliations: list('affiliations'),
    maps: list('maps'), miscItems: list('miscItems'), giftItems: list('giftItems'), quests: list('quests'),
    supports: supports.Pairs.map((p) => ({ a: p.First, b: p.Second, flags: p.Flags })),
    none: '—',
  };
  fs.mkdirSync(OUT, { recursive: true });
  const file = path.join(OUT, `data-${lang}.js`);
  fs.writeFileSync(file, '// generated by tools/build-data.mjs - do not edit by hand\nwindow.FE3H_DATA = window.FE3H_DATA || {};\nwindow.FE3H_DATA[' + JSON.stringify(lang) + '] = ' + JSON.stringify(data) + ';\n');
  console.log('  ' + lang.padEnd(6) + path.basename(file).padEnd(16) + (fs.statSync(file).size / 1024).toFixed(0) + ' KB · '
    + Object.keys(itemDb).length + ' items, ' + chars.length + ' units, ' + classes.length + ' classes, '
    + supports.Pairs.length + ' conversations');
}
